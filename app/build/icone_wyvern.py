# Ícone do MHLAUNCHER: uma cabeça de wyvern original em pixel art (32x32), ampliada sem borrar para 256 e 512 px.
# Desenho próprio (não é arte da Capcom): chifres para trás, boca aberta com presas, olho dourado e o pescoço
# descendo, dentro de um selo redondo de couro com borda em brasa.
# Rodar: python icone_wyvern.py -> icon.png (512) e ../src/renderer/img/icone.png (256)
import math, os, sys
from PIL import Image

AQUI = os.path.dirname(os.path.abspath(sys.argv[0]))
COR = {
    "o": (26, 12, 10), "r": (192, 50, 36), "R": (236, 98, 66), "d": (118, 26, 22), "g": (206, 150, 64),
    "G": (246, 214, 140), "e": (255, 224, 116), "w": (242, 233, 216),
}
BORDA, BORDA2, COURO, COURO2 = (226, 96, 63), (150, 52, 32), (40, 32, 27), (30, 24, 20)
# '.' = o fundo do selo aparece
WYVERN = """
................................
................................
...........................o....
..........................oGo...
.....................oo.........
....................oGGo........
...................oGgo..oo.....
..................oGgoooGGo.....
..............oooooggggGgo......
............ooRRRRoogggoo.......
..........ooRRRrrrrrooo.........
........ooRRrrrrrrrrrdo.........
......ooRRrrrroooorrrddo........
.....oRRrrrrrrroeGorrddo........
....oRrrrrrrrrrrrrrrrdddo.......
...oRrrrrrrrrrrrrrrrrdddo.......
..oRrrrrrrrrrrrrrrrrrdddoo......
..oRrrrrrrrrrrrrrrrrrddddo......
..ooowwowwowoooorrrrrddddo......
...o..............orrrdddddo....
..oowwowwowoooooorrrrdddddo.....
..oddddddddddddddrrrdddddddo....
...ooddddddddddddddddddddddo....
.....ooooooooodddddddddddddo....
..............oodddddddddddo....
................oddddddddddo....
.................oddddddddddo...
.................odddddddddddo..
..................oddddddddddo..
...................odddddddddo..
...................oddddddddo...
................................
""".strip("\n").split("\n")
WYVERN = [l.ljust(32, ".")[:32] for l in WYVERN] + ["." * 32] * (32 - len(WYVERN))

img = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
c = 15.5
for y in range(32):
    for x in range(32):
        r = math.hypot(x - c, y - c)
        if r > 15.6: continue
        if r > 14.2: img.putpixel((x, y), BORDA + (255,)); continue
        if r > 13.4: img.putpixel((x, y), BORDA2 + (255,)); continue
        ch = WYVERN[y][x]
        if ch in COR: img.putpixel((x, y), COR[ch] + (255,))
        else: img.putpixel((x, y), (COURO if (x + y) % 7 else COURO2) + (255,))
img.resize((512, 512), Image.NEAREST).save(os.path.join(AQUI, "icon.png"))
img.resize((256, 256), Image.NEAREST).save(os.path.join(AQUI, "..", "src", "renderer", "img", "icone.png"))
print("ok")
